#!/usr/bin/env python3
"""Split each interior decor strip into its individual swatches.

Jayco publishes a decor as one 1200x276 strip: four to six square material
swatches in a row, each with its name set in caps underneath. The model page
shows them as separate pieces with live labels, so this cuts every strip in
assets/model details/finishes/*__decor-*.webp into one WebP per swatch and
reads each label with tesseract.

Writes:
  assets/model details/finishes/pieces/<strip>--<n>.webp
  version-5/js/decor-pieces-data.js   (window.JAYCO_DECOR_PIECES)

Run from anywhere:  python3 version-5/tools/crop-decor-swatches.py
Needs Pillow, numpy and tesseract (brew install tesseract).
Re-run after adding or replacing a decor strip; the output is regenerated
whole. Check the printed labels: tesseract occasionally picks up a stray mark.
"""
import glob
import json
import os
import re
import statistics
import subprocess
import tempfile

import numpy as np
from PIL import Image, ImageOps

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'model details', 'finishes')
OUT = os.path.join(SRC, 'pieces')
DATA = os.path.join(ROOT, 'version-5', 'js', 'decor-pieces-data.js')

# Jayco's caps, as the site sets them: sentence case, abbreviations spelled out
LABEL_FIX = {'WOOD ACC.': 'Wood accent'}


def label_case(raw):
    t = re.sub(r'[^A-Z .]', '', raw.upper()).strip()
    t = re.sub(r'\s+', ' ', t)
    return LABEL_FIX.get(t, t.capitalize())


def runs(mask):
    """[start, end) of each True run"""
    out, s = [], None
    for x, v in enumerate(mask):
        if v and s is None:
            s = x
        if not v and s is not None:
            out.append((s, x))
            s = None
    if s is not None:
        out.append((s, len(mask)))
    return out


def slots(im):
    """Left edges and size of every swatch in the strip.

    Swatches are found as columns that are mostly not white. A near-white
    swatch (a marble countertop) can read as background, so a gap of more than
    one and a half steps between found swatches gets the missing one filled
    in, and the row is extended to either edge on the same step."""
    a = np.array(im).astype(int)
    H, W = a.shape[:2]
    white = (a[:, :, 0] > 245) & (a[:, :, 1] > 245) & (a[:, :, 2] > 245)
    cols = (~white[:int(H * 0.8)]).mean(axis=0) > 0.5
    segs = [g for g in runs(cols) if g[1] - g[0] > 30]
    w = int(statistics.median(g[1] - g[0] for g in segs))
    full = [g[0] for g in segs if abs((g[1] - g[0]) - w) <= 8]
    step = min(full[i + 1] - full[i] for i in range(len(full) - 1))

    xs = [full[0]]
    for x in full[1:]:
        while x - xs[-1] > step * 1.5:
            xs.append(xs[-1] + step)
        xs.append(x)
    while xs[0] - step >= 0:
        xs.insert(0, xs[0] - step)
    while xs[-1] + step + w <= W + 2:
        xs.append(xs[-1] + step)

    rows = (~white[:, full[0]:full[0] + w]).mean(axis=1) > 0.9
    ys = np.nonzero(rows)[0]
    return xs, w, int(ys[0]), int(ys[-1]) + 1


def read_label(im, x, w, y0, tmp):
    W, H = im.size
    lab = im.crop((max(0, x - 12), y0 + 2, min(W, x + w + 12), H))
    if (np.array(lab.convert('L')) < 150).sum() < 20:
        return None                         # an empty slot past the last swatch
    g = ImageOps.grayscale(lab)
    g = g.resize((g.width * 3, g.height * 3))
    g.save(tmp)
    return subprocess.run(['tesseract', tmp, '-', '--psm', '7'],
                          capture_output=True, text=True).stdout.strip()


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in glob.glob(os.path.join(OUT, '*.webp')):
        os.remove(f)
    tmp = os.path.join(tempfile.mkdtemp(), 'label.png')
    data = {}
    for path in sorted(glob.glob(os.path.join(SRC, '*__decor-*.webp'))):
        name = os.path.basename(path)
        im = Image.open(path).convert('RGB')
        xs, w, y0, y1 = slots(im)
        pieces = []
        for x in xs:
            raw = read_label(im, x, w, y1, tmp)
            if raw is None:
                continue
            n = len(pieces) + 1
            out = name[:-5] + '--' + str(n) + '.webp'
            # 1px in from every edge, clear of any anti-aliased border
            im.crop((x + 1, y0 + 1, x + w - 1, y1 - 1)).save(
                os.path.join(OUT, out), 'WEBP', quality=90, method=6)
            pieces.append({'label': label_case(raw), 'img': out,
                           'w': w - 2, 'h': y1 - y0 - 2})
        data[name] = pieces
        print(name, [p['label'] for p in pieces])

    with open(DATA, 'w') as fh:
        fh.write('/* GENERATED by tools/crop-decor-swatches.py — do not edit by hand.\n'
                 '   Each interior decor strip in finishes-data.js, split into its\n'
                 '   swatches, keyed by the strip\'s file name. Labels are Jayco\'s,\n'
                 '   read off the strip and set in sentence case. */\n')
        fh.write('window.JAYCO_DECOR_PIECES = ' + json.dumps(data, indent=1) + ';\n')


if __name__ == '__main__':
    main()
